const port = (n: string) => PORTS.find((p) => p.n === n)!.at;

/** A route as a quadratic curve, `bend` pushing its middle sideways (in projected units). */
function route(a: string, b: string, bend: number, via?: P): string {
  const [x1, y1] = prj(port(a));
  const [x2, y2] = prj(port(b));
  let cx: number, cy: number;
  if (via) [cx, cy] = prj(via);
  else {
    const mx = (x1 + x2) / 2, my = (y1 + y2) / 2, len = Math.hypot(x2 - x1, y2 - y1);
    cx = mx + (-(y2 - y1) / len) * bend; cy = my + ((x2 - x1) / len) * bend;
  }
  return `M ${x1.toFixed(1)} ${y1.toFixed(1)} Q ${cx.toFixed(1)} ${cy.toFixed(1)} ${x2.toFixed(1)} ${y2.toFixed(1)}`;
}

