export function NetworkMap() {
  const grat = [];
  const gratT = [];
  for (let lon = -2; lon <= 10; lon += 2) {
    const [x] = prj([lon, 0]);
    grat.push(<path key={`lo${lon}`} className="hy-grat" d={`M ${x.toFixed(1)} 0 V ${MAP_H}`} />);
    gratT.push(<text key={`lot${lon}`} className="hy-grat-t" x={x + 4} y={MAP_H - 8}>{Math.abs(lon)}°{lon < 0 ? 'W' : lon > 0 ? 'E' : ''}</text>);
  }
  for (let lat = 51; lat <= 60; lat += 1) {
    const [, yy] = prj([0, lat]);
    grat.push(<path key={`la${lat}`} className="hy-grat" d={`M 0 ${yy.toFixed(1)} H ${MAP_W}`} />);
    if (lat % 2 === 0) gratT.push(<text key={`lat${lat}`} className="hy-grat-t" x={6} y={yy - 5}>{lat}°N</text>);
  }

  return (
    <svg className="hy-map-svg" viewBox={`0 0 ${MAP_W} ${MAP_H}`} role="img" aria-label="Map of the North Sea showing Halyard's seven routes from Rotterdam, Zeebrugge, Cuxhaven and Esbjerg to Immingham, Teesport, Rosyth, Aberdeen and Bergen">
      <rect className="hy-sea" width={MAP_W} height={MAP_H} />
      {grat}
      <g className="hy-land">
        <path d={ring(GB)} />
        <path d={ring(NORWAY)} />
        <path d={ring(CONTINENT)} />
        {ISLANDS.map((p, i) => <path key={i} d={ring(p)} />)}
      </g>
      {gratT}
      {LABELS.map((l) => {
        const [x, yy] = prj(l.at);
        return <text key={l.t} className={`hy-map-l ${l.cls ?? ''}`} x={x.toFixed(1)} y={yy.toFixed(1)} textAnchor={l.anchor ?? 'middle'}>{l.t}</text>;
      })}
      <g>
        {LINES.map((l, i) => <path key={i} className={`hy-route${l.isNew ? ' is-new' : ''}`} d={l.d} />)}
      </g>
      {PORTS.map((p) => {
        const [x, yy] = prj(p.at);
        return (
          <g key={p.n} className={`hy-port${p.hq ? ' is-hq' : ''}`}>
            <circle cx={x.toFixed(1)} cy={yy.toFixed(1)} r={p.hq ? 6 : 4} />
            <text x={(x + p.dx).toFixed(1)} y={(yy + p.dy).toFixed(1)} textAnchor={p.anchor ?? 'start'}>{p.n}</text>
          </g>
        );
      })}
      <g className="hy-scale" transform={`translate(${MAP_W - NM100 - 24} ${MAP_H - 40})`}>
        <path d={`M 0 0 H ${NM100} M 0 -4 V 4 M ${NM100 / 2} -3 V 3 M ${NM100} -4 V 4`} />
        <text x="0" y="-9">0</text>
        <text x={NM100} y="-9" textAnchor="end">100 nm</text>
      </g>
      <g className="hy-north" transform={`translate(${MAP_W - 30} 34)`}>
        <path d="M 0 -16 L 7 8 L 0 3 L -7 8 Z" />
        <text x="0" y="24" textAnchor="middle">N</text>
      </g>
    </svg>
  );
}
